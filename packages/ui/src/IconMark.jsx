export function resolveIcon(name, extra) {
  return (extra && extra[name]) || ICONS[name] || Layers
}

export default function IconMark({ name, size = 16, strokeWidth = 1.6 }) {
  const { icons } = useShell()
  const Icon = resolveIcon(name, icons)
  return <Icon size={size} strokeWidth={strokeWidth} aria-hidden="true" />
}
